"""Train/sample conditional DDPM appearance grids for a frozen SpatialLanderAE.

DDPM epsilon training; DDIM sampling with unique timesteps and correct jumps.
Source image + observed state/action context + requested future pose -> future
16x6x8 appearance. The decoder receives the requested future pose explicitly.
No existing 128-D score-network weights are used. Test shard is excluded from
training, normalization, validation selection and intermediate previews.
"""
