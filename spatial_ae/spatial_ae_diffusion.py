def seed_all(seed):
    random.seed(seed); np.random.seed(seed); torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)
    torch.backends.cudnn.benchmark = False
    torch.backends.cudnn.deterministic = True


def device():
    return torch.device('cuda' if torch.cuda.is_available() else 'cpu')


def clean_json(value):
    if isinstance(value, dict):
        return {str(k): clean_json(v) for k, v in value.items()}
    if isinstance(value, (list, tuple)):
        return [clean_json(v) for v in value]
    if isinstance(value, (np.integer, np.bool_)):
        return value.item()
    if isinstance(value, (float, np.floating)):
        return float(value) if np.isfinite(value) else None
    return value


def write_json(path, value):
    Path(path).write_text(json.dumps(clean_json(value), indent=2, allow_nan=False) + '\n')


def save_pt(path, value):
    path = Path(path)
    tmp = path.with_suffix('.partial.pt')
    torch.save(value, tmp); tmp.replace(path)


def load_pt(path):
    # These are trusted local checkpoints generated by this workflow.
    return torch.load(path, map_location='cpu', weights_only=False)


def load_ae(path, dev, expected_hash=None):
    from train_lander_spatial_ae import load_spatial
    digest = file_hash(path)
    if expected_hash is not None and digest != expected_hash:
        raise ValueError('AE checkpoint differs from cached/trained AE; do not mix latent spaces')
    model, epoch = load_spatial(path, dev)
    model.eval().requires_grad_(False)
    return model, dict(path=str(Path(path).resolve()), sha256=digest, epoch=int(epoch),
                       channels=int(model.appearance_channels), spatial_shape=[6, 8])


def pose_features(pose):
    return torch.cat((pose[:, :2], pose[:, 2:3].sin(), pose[:, 2:3].cos()), dim=1)


def condition(source_pose, future_pose, context_raw, actions):
    return torch.cat((pose_features(source_pose), pose_features(future_pose),
                      context_raw.flatten(1), F.one_hot(actions.long(), 4).float().flatten(1)), dim=1)


def collect_files(a):
    root, test_root = Path(a.train_root).resolve(), Path(a.test_root).resolve()
    if not root.is_dir() or not test_root.is_dir():
        raise FileNotFoundError('Missing trajectory root. Check --train-root and --test-root')
    tests = sorted(test_root.rglob('*.npz'))
    if a.max_test_files:
        tests = tests[:a.max_test_files]
    candidates = sorted(p for p in root.rglob('*.npz')
                        if test_root not in p.parents and a.exclude_shard not in p.parts)
    if not tests or len(candidates) < 3:
        raise ValueError('Need training trajectories outside the excluded test shard plus test files')
    rng = np.random.default_rng(a.seed)
    # Sample across available shards instead of taking only the first shard.
    if a.max_train_files and len(candidates) > a.max_train_files:
        candidates = [candidates[i] for i in sorted(rng.choice(len(candidates), a.max_train_files, replace=False))]
    seen = {}
    unique, duplicate = [], []
    for path in tests + candidates:
        digest = file_hash(path)
        if digest in seen:
            if path in tests:
                duplicate.append(dict(path=str(path), duplicate_of=seen[digest]))
                continue
            if Path(seen[digest]) in tests:
                raise ValueError(f'Training archive exactly duplicates test archive: {path}')
            duplicate.append(dict(path=str(path), duplicate_of=seen[digest]))
            continue
        seen[digest] = str(path)
        unique.append(path)
    tests = [p for p in unique if p in tests]
    train_files = [p for p in unique if p in candidates and p not in tests]
    train, val = split_archives(train_files, a.val_fraction, a.seed)
    return dict(train=train, val=val, test=tests), duplicate


def prepare(a):
    seed_all(a.seed)
    out = Path(a.out).resolve()
    if (out / 'manifest.json').exists():
        raise FileExistsError(f'Cache exists: {out}; use a new directory')
    out.mkdir(parents=True, exist_ok=True)
    ae, ae_info = load_ae(a.ae_checkpoint, device())
    files, duplicate = collect_files(a)
    manifest = dict(format=FORMAT, settings=vars(a), ae=ae_info, splits={}, duplicates=duplicate,
                    horizon=a.horizon, pose_columns=list(a.pose_cols), xy_scales=list(a.xy_scales),
                    xy_offsets=list(a.xy_offsets), torch_version=torch.__version__,
                    script_sha256=file_hash(__file__),
                    note='Archive/trajectory split. Exact-file deduplication does not rule out correlated trajectories.')
    for split, paths in files.items():
        values = {k: [] for k in ('source', 'future', 'source_pose', 'future_pose', 'future_encoded_pose',
                                  'context_raw', 'actions', 'future_rgb', 'identity')}
        path_manifest, omitted = [], Counter()
        for archive_index, path in enumerate(paths):
            episodes = load_episodes(path)
            path_manifest.append(dict(path=str(path), sha256=file_hash(path), episodes=len(episodes)))
            for episode_index, (frames, states, actions, done) in enumerate(episodes):
                starts = pair_indices(len(frames), actions, done, a.horizon)
                omitted['short_or_terminal_pairs'] += max(0, len(frames)-a.horizon) - len(starts)
                if not starts:
                    omitted['empty_episodes'] += 1; continue
                encoded = []
                for j in range(0, len(frames), a.encode_batch):
                    tensor = torch.from_numpy(frames[j:j+a.encode_batch].copy()).permute(0, 3, 1, 2).float().to(device()) / 255.
                    with torch.no_grad():
                        encoded.append(ae.encode_latent(tensor).cpu())
                encoded = torch.cat(encoded)
                if not torch.isfinite(encoded).all():
                    raise ValueError(f'Nonfinite AE encoding: {path}')
                src = torch.tensor(starts, dtype=torch.long)
                dst = src + a.horizon
                appearance = encoded[:, 3:].reshape(-1, ae_info['channels'], 6, 8)
                values['source'].append(appearance[src])
                values['future'].append(appearance[dst])
                values['source_pose'].append(encoded[src, :3])
                values['future_encoded_pose'].append(encoded[dst, :3])
                values['future_pose'].append(torch.from_numpy(physical_pose(states[dst.numpy()], a.pose_cols, a.xy_scales, a.xy_offsets)))
                values['context_raw'].append(torch.from_numpy(np.stack([states[i:i+a.horizon] for i in starts])))
                values['actions'].append(torch.from_numpy(np.stack([actions[i:i+a.horizon] for i in starts])))
                values['future_rgb'].append(torch.from_numpy(frames[dst.numpy()].copy()))
                values['identity'].append(torch.tensor([[archive_index, episode_index, i] for i in starts], dtype=torch.long))
            if (archive_index+1) % 20 == 0 or archive_index+1 == len(paths):
                print(f'Encoded {split}: {archive_index+1}/{len(paths)} trajectories', flush=True)
        if not values['source']:
            raise ValueError(f'No valid future pairs in {split}')
        data = {key: torch.cat(items) for key, items in values.items()}
        cap = a.max_train_pairs if split == 'train' else (a.max_eval_pairs if split == 'test' else 0)
        before = len(data['source'])
        if cap and before > cap:
            ids = torch.from_numpy(np.sort(np.random.default_rng(a.seed).choice(before, cap, replace=False)))
            data = {key: tensor[ids] for key, tensor in data.items()}
        data.update(format=FORMAT, ae_sha256=ae_info['sha256'], horizon=a.horizon,
                    pose_columns=list(a.pose_cols), xy_scales=list(a.xy_scales), xy_offsets=list(a.xy_offsets),
                    files=path_manifest)
        save_pt(out / f'{split}.pt', data)
        manifest['splits'][split] = dict(archives=path_manifest, pairs_before_cap=before,
                                        pairs=len(data['source']), exclusions=dict(omitted),
                                        cache_sha256=file_hash(out / f'{split}.pt'))
        del data, values
    write_json(out / 'manifest.json', manifest)
    print(json.dumps({s: dict(trajectories=len(files[s]), pairs=manifest['splits'][s]['pairs']) for s in files}, indent=2), flush=True)
    print(f'Prepared cache: {out}', flush=True)


class CachedPairs(Dataset):
    def __init__(self, path, expected_ae):
        self.data = load_pt(path)
        if self.data.get('format') != FORMAT or self.data['ae_sha256'] != expected_ae:
            raise ValueError(f'Cache/checkpoint mismatch: {path}')
    def __len__(self):
        return len(self.data['source'])
    def __getitem__(self, i):
        return {k: self.data[k][i] for k in ('source', 'future', 'source_pose', 'future_pose',
                 'future_encoded_pose', 'context_raw', 'actions', 'future_rgb', 'identity')}


def normalization(data):
    both = torch.cat((data['source'], data['future']))
    mean = both.mean((0, 2, 3), keepdim=True)
    std = both.std((0, 2, 3), unbiased=False, keepdim=True).clamp_min(1e-3)
    cond = condition(data['source_pose'], data['future_pose'], data['context_raw'], data['actions'])
    cm, cs = cond.mean(0, keepdim=True), cond.std(0, unbiased=False, keepdim=True).clamp_min(.05)
    # Preserve action one-hot encoding instead of amplifying rare/missing categories.
    action_width = data['actions'].shape[1] * 4
    cm[:, -action_width:] = 0; cs[:, -action_width:] = 1
    return dict(mean=mean, std=std, cond_mean=cm, cond_std=cs)


class ResidualBlock(nn.Module):
    def __init__(self, width, embedding, dilation):
        super().__init__()
        self.norm1, self.norm2 = nn.GroupNorm(8, width), nn.GroupNorm(8, width)
        self.conv1 = nn.Conv2d(width, width, 3, padding=dilation, dilation=dilation)
        self.conv2 = nn.Conv2d(width, width, 3, padding=1)
        self.film = nn.Linear(embedding, width * 2)
    def forward(self, x, embedding):
        h = self.conv1(F.silu(self.norm1(x)))
        scale, shift = self.film(F.silu(embedding)).chunk(2, 1)
        h = self.norm2(h) * (1 + scale[:, :, None, None]) + shift[:, :, None, None]
        return x + self.conv2(F.silu(h))


class SpatialDenoiser(nn.Module):
    def __init__(self, channels, cond_dim, width=96, blocks=6, time_dim=128):
        super().__init__()
        self.channels, self.time_dim = channels, time_dim
        self.time = nn.Sequential(nn.Linear(time_dim, width*2), nn.SiLU(), nn.Linear(width*2, width*2))
        self.cond = nn.Sequential(nn.Linear(cond_dim, width*2), nn.SiLU(), nn.Linear(width*2, width*2))
        self.input = nn.Conv2d(channels * 2 + 2, width, 3, padding=1)
        self.blocks = nn.ModuleList([ResidualBlock(width, width*2, 1 if i % 2 == 0 else 2) for i in range(blocks)])
        self.output = nn.Sequential(nn.GroupNorm(8, width), nn.SiLU(), nn.Conv2d(width, channels, 3, padding=1))
    def forward(self, noisy, timestep, source, cond):
        frequencies = torch.exp(-math.log(10000) * torch.arange(self.time_dim//2, device=noisy.device) / (self.time_dim//2 - 1))
        phase = timestep.float()[:, None] * frequencies[None]
        embedding = self.time(torch.cat((phase.sin(), phase.cos()), 1)) + self.cond(cond)
        yy, xx = torch.meshgrid(torch.linspace(-1, 1, noisy.shape[2], device=noisy.device),
                                torch.linspace(-1, 1, noisy.shape[3], device=noisy.device), indexing='ij')
        coords = torch.stack((xx, yy))[None].expand(noisy.shape[0], -1, -1, -1)
        h = self.input(torch.cat((noisy, source, coords), 1))
        for block in self.blocks:
            h = block(h, embedding)
        return self.output(h)


class Schedule:
    def __init__(self, steps, dev):
        # Cosine alpha-bar schedule with beta bounded away from singularity.
        f = torch.cos(((torch.arange(steps+1, dtype=torch.float64) / steps + .008) / 1.008) * math.pi/2).square()
        abar = f / f[0]
        beta = (1 - abar[1:] / abar[:-1]).clamp(.000001, .999)
        self.alpha = torch.cumprod(1 - beta, 0).float().to(dev)
        self.steps = steps
    def add_noise(self, clean, time, noise):
        alpha = self.alpha[time].view(-1, 1, 1, 1)
        return alpha.sqrt() * clean + (1-alpha).sqrt() * noise
    def clean(self, noisy, time, predicted_noise):
        alpha = self.alpha[time].view(-1, 1, 1, 1)
        return (noisy - (1-alpha).sqrt() * predicted_noise) / alpha.sqrt()


def decode(ae, pose, appearance):
    return ae.decode(torch.cat((pose, appearance.flatten(1)), 1))


def auxiliary_loss(prediction, target_bytes):
    from train_lander_spatial_ae import soft_mask_log
    target = target_bytes.permute(0, 3, 1, 2).float() / 255.
    r, g, b = target.unbind(1)
    mask = ((b > 100/255) & (b > g + 20/255) & (r > 50/255) & (r < 220/255)).float()
    soft = soft_mask_log(prediction).exp()
    dice = 1 - (2*(soft*mask).sum((1, 2)) + 1) / (soft.sum((1, 2)) + mask.sum((1, 2)) + 1)
    edge = prediction.new_zeros(len(prediction))
    for dim in (1, 2):
        pd, td = torch.diff(soft, dim=dim), torch.diff(mask, dim=dim)
        edge = edge + (pd-td).abs().sum((1, 2)) / (td.abs().sum((1, 2)) + 1)
    roi = F.max_pool2d(mask[:, None], 5, stride=1, padding=2)
    rgb = ((prediction-target).abs() * roi).sum((1, 2, 3)) / (roi.sum((1, 2, 3)) * 3).clamp_min(1)
    rgb = rgb + .1 * (prediction-target).abs().mean((1, 2, 3))
    return (dice + .25*edge).mean(), rgb.mean()


def batch_loss(model, ae, batch, norm, schedule, a, generator):
    dev = schedule.alpha.device
    batch = {k: v.to(dev) for k, v in batch.items()}
    src, future = [(batch[k]-norm['mean'])/norm['std'] for k in ('source', 'future')]
    cond = (condition(batch['source_pose'], batch['future_pose'], batch['context_raw'], batch['actions']) - norm['cond_mean']) / norm['cond_std']
    t = torch.randint(schedule.steps, (len(src),), device=dev, generator=generator)
    noise = torch.randn(future.shape, device=dev, generator=generator)
    noisy = schedule.add_noise(future, t, noise)
    estimate = model(noisy, t, src, cond)
    epsilon = F.mse_loss(estimate, noise)
    shape, rgb = epsilon.new_zeros(()), epsilon.new_zeros(())
    keep = t < a.aux_max_t
    if keep.any() and (a.shape_weight or a.rgb_weight):
        clean = schedule.clean(noisy[keep], t[keep], estimate[keep])
        prediction = decode(ae, batch['future_pose'][keep], clean * norm['std'] + norm['mean'])
        shape, rgb = auxiliary_loss(prediction, batch['future_rgb'][keep])
    total = epsilon + a.shape_weight * shape + a.rgb_weight * rgb
    if not torch.isfinite(total):
        raise RuntimeError('Nonfinite training objective')
    return total, torch.stack((total.detach(), epsilon.detach(), shape.detach(), rgb.detach()))


@torch.no_grad()
def sample_grid(model, schedule, source, source_pose, requested_pose, context, actions, norm,
                sampling_steps=50, noise=None, clip=8., snapshots=False):
    """Target-free inference: no future image or future appearance argument."""
    if not 2 <= sampling_steps <= schedule.steps:
        raise ValueError('Sampling steps must be between 2 and trained diffusion steps')
    src = (source - norm['mean']) / norm['std']
    cond = (condition(source_pose, requested_pose, context, actions) - norm['cond_mean']) / norm['cond_std']
    latent = torch.randn_like(src) if noise is None else noise.clone()
    times = torch.linspace(schedule.steps - 1, 0, sampling_steps).round().long().tolist()
    if len(times) != len(set(times)):
        raise AssertionError('Repeated DDIM timesteps')
    previews = []
    for i, time in enumerate(times):
        tt = torch.full((len(src),), time, device=src.device, dtype=torch.long)
        alpha = schedule.alpha[time]
        # Use the actual next selected timestep, never time-1 for a jumped schedule.
        previous = schedule.alpha[times[i+1]] if i+1 < len(times) else latent.new_tensor(1.)
        epsilon = model(latent, tt, src, cond)
        clean = (latent - (1-alpha).sqrt()*epsilon) / alpha.sqrt()
        if clip > 0:
            clean = clean.clamp(-clip, clip)
            epsilon = (latent - alpha.sqrt()*clean) / (1-alpha).sqrt()
        latent = previous.sqrt()*clean + (1-previous).sqrt()*epsilon
        if snapshots and i in (0, len(times)//2, len(times)-1):
            previews.append(clean * norm['std'] + norm['mean'])
    if not torch.isfinite(latent).all():
        raise RuntimeError('Nonfinite sampled grid')
    return latent * norm['std'] + norm['mean'], previews


def cache_manifest(path):
    manifest = json.loads((Path(path) / 'manifest.json').read_text())
    if manifest['format'] != FORMAT:
        raise ValueError('Unsupported cache version')
    return manifest


def verify_cache_files(cache, manifest, splits):
    for split in splits:
        path = Path(cache)/f'{split}.pt'
        if file_hash(path) != manifest['splits'][split]['cache_sha256']:
            raise ValueError(f'{split} cache changed after preparation; rebuild instead of mixing data')


def eval_loss(model, ae, loader, norm, schedule, a):
    model.eval()
    generator = torch.Generator(device=schedule.alpha.device).manual_seed(a.seed + 1901)
    values, n = np.zeros(4), 0
    with torch.no_grad():
        for batch in loader:
            _, parts = batch_loss(model, ae, batch, norm, schedule, a, generator)
            size = len(batch['source']); values += parts.cpu().numpy() * size; n += size
    return (values/n).tolist()


def render_panel(path, images, titles):
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    cols = 3
    rows = math.ceil(len(images)/cols)
    fig, axes = plt.subplots(rows, cols, figsize=(12, rows*3.8), squeeze=False)
    for axis in axes.flat:
        axis.axis('off')
    for axis, image, title in zip(axes.flat, images, titles):
        if isinstance(image, torch.Tensor):
            image = image.detach().cpu().permute(1, 2, 0).numpy()
        axis.imshow(np.clip(image, 0, 1), interpolation='nearest'); axis.set_title(title, fontsize=10)
    fig.tight_layout(); fig.savefig(path, dpi=140); plt.close(fig)


@torch.no_grad()
def val_preview(model, ae, data, norm, schedule, a, directory):
    directory.mkdir(parents=True, exist_ok=True)
    rng = np.random.default_rng(a.seed)
    indices = rng.choice(len(data['source']), min(a.preview_n, len(data['source'])), replace=False)
    dev = schedule.alpha.device
    generator = torch.Generator(device=dev).manual_seed(a.seed + 17)
    for i in indices:
        b = {k: data[k][i:i+1].to(dev) for k in ('source', 'source_pose', 'future_pose', 'context_raw', 'actions', 'future', 'future_encoded_pose')}
        noise = torch.randn(b['source'].shape, device=dev, generator=generator)
        result, _ = sample_grid(model, schedule, b['source'], b['source_pose'], b['future_pose'], b['context_raw'], b['actions'], norm, a.sample_steps, noise, a.clip_x0)
        target = data['future_rgb'][i].float().permute(2, 0, 1)/255.
        plain = decode(ae, b['future_encoded_pose'], b['future'])[0]
        swap = decode(ae, b['future_pose'], b['source'])[0]
        predicted = decode(ae, b['future_pose'], result)[0]
        render_panel(directory / f'pair_{i:06d}.png', [target, plain, swap, predicted],
                     ['Real future', 'AE of real future (reference)', 'Source appearance + future pose', 'Diffusion: requested true future pose'])


def train(a):
    seed_all(a.seed)
    dev, out = device(), Path(a.out).resolve()
    manifest = cache_manifest(a.cache)
    verify_cache_files(a.cache, manifest, ('train', 'val'))
    ae, ae_info = load_ae(a.ae_checkpoint, dev, manifest['ae']['sha256'])
    datasets = {s: CachedPairs(Path(a.cache)/f'{s}.pt', ae_info['sha256']) for s in ('train', 'val')}
    if datasets['train'].data['context_raw'].shape[1:] != datasets['val'].data['context_raw'].shape[1:]:
        raise ValueError('Train/validation raw state shapes differ')
    if (out/'last.pt').exists() and not a.resume:
        raise FileExistsError(f'Training output exists: {out}; pass --resume or use a new directory')
    out.mkdir(parents=True, exist_ok=True)
    norm_cpu = normalization(datasets['train'].data)
    model_config = dict(channels=ae_info['channels'], cond_dim=norm_cpu['cond_mean'].shape[1], width=a.width, blocks=a.blocks)
    model = SpatialDenoiser(**model_config).to(dev)
    ema = copy.deepcopy(model).eval().requires_grad_(False)
    optimizer = torch.optim.AdamW(model.parameters(), lr=a.lr, weight_decay=1e-4)
    norm = {k: v.to(dev) for k, v in norm_cpu.items()}
    schedule = Schedule(a.diffusion_steps, dev)
    start, best = 0, float('inf')
    cache_digest = file_hash(Path(a.cache)/'manifest.json')
    if a.resume:
        if Path(a.resume).resolve().parent != out:
            raise ValueError('Resume into the original model directory so its selected best.pt is retained')
        saved = load_pt(a.resume)
        required = dict(model_config=model_config, cache_sha256=cache_digest, ae_sha256=ae_info['sha256'])
        if saved.get('format') != FORMAT or any(saved.get(k) != v for k, v in required.items()):
            raise ValueError('Resume checkpoint architecture/cache/AE mismatch')
        for key in ('diffusion_steps', 'shape_weight', 'rgb_weight', 'aux_max_t', 'ema_decay', 'batch_size', 'seed', 'lr'):
            if saved['settings'][key] != getattr(a, key):
                raise ValueError(f'Resume setting changed: {key}')
        model.load_state_dict(saved['model']); ema.load_state_dict(saved['ema'])
        optimizer.load_state_dict(saved['optimizer'])
        norm_cpu = saved['normalization']; norm = {k: v.to(dev) for k, v in norm_cpu.items()}
        start, best = saved['epoch'], saved['best_validation']
    if start >= a.epochs:
        raise ValueError('--epochs must exceed resumed epoch')
    loaders = {s: DataLoader(datasets[s], batch_size=a.batch_size, shuffle=False, num_workers=0) for s in datasets}
    config = dict(settings=vars(a), model_config=model_config, ae=ae_info, cache_sha256=cache_digest,
                  train_pairs=len(datasets['train']), val_pairs=len(datasets['val']),
                  objective='epsilon MSE + low-noise decoded future silhouette and purple RGB',
                  future_pose='known true pose during training/validation; independent dynamics at final evaluation',
                  normalization='train split only', script_sha256=file_hash(__file__))
    write_json(out/'config.json', config)
    print(json.dumps(config, indent=2), flush=True)
    print('AE weights frozen. New spatial denoiser trained from scratch. No test data used for selection.', flush=True)
    if start == 0:
        pose_probe(ae, datasets['val'].data, dev, out/'pose_probe', a)
    for epoch in range(start+1, a.epochs+1):
        model.train()
        generator = torch.Generator(device=dev).manual_seed(a.seed + epoch * 1009)
        order = torch.Generator().manual_seed(a.seed + epoch)
        loader = DataLoader(datasets['train'], batch_size=a.batch_size, shuffle=True, generator=order, num_workers=0)
        sums, n = np.zeros(4), 0
        for step, batch in enumerate(loader, 1):
            optimizer.zero_grad(set_to_none=True)
            total, parts = batch_loss(model, ae, batch, norm, schedule, a, generator)
            total.backward()
            gradient_norm = torch.nn.utils.clip_grad_norm_(model.parameters(), 1.)
            if not torch.isfinite(gradient_norm):
                raise RuntimeError('Nonfinite denoiser gradient')
            optimizer.step()
            with torch.no_grad():
                for dest, src in zip(ema.parameters(), model.parameters()):
                    dest.mul_(a.ema_decay).add_(src, alpha=1-a.ema_decay)
            size = len(batch['source']); sums += parts.cpu().numpy() * size; n += size
            if step % 100 == 0:
                print(f'Epoch {epoch}/{a.epochs} batch {step}/{len(loader)} total={float(total.detach()):.5f}', flush=True)
        validation = eval_loss(ema, ae, loaders['val'], norm, schedule, a)
        improved = validation[0] < best
        if improved:
            best = validation[0]
        payload = dict(format=FORMAT, model=model.state_dict(), ema=ema.state_dict(), optimizer=optimizer.state_dict(),
                       epoch=epoch, best_validation=best, validation=validation, model_config=model_config,
                       normalization=norm_cpu, ae_sha256=ae_info['sha256'], cache_sha256=cache_digest,
                       settings=vars(a), horizon=manifest['horizon'],
                       pose_columns=manifest['pose_columns'], xy_scales=manifest['xy_scales'], xy_offsets=manifest['xy_offsets'])
        save_pt(out/'last.pt', payload)
        if improved:
            save_pt(out/'best.pt', payload)
        if epoch % a.save_every == 0:
            save_pt(out/f'epoch_{epoch}.pt', payload)
            val_preview(ema, ae, datasets['val'].data, norm, schedule, a, out/f'validation_epoch_{epoch}')
        with (out/'training.jsonl').open('a') as f:
            f.write(json.dumps(dict(epoch=epoch, train=(sums/n).tolist(), validation=validation, best=improved))+'\n')
        print(f'Epoch {epoch}: train={(sums/n).tolist()} validation={validation} selected={improved}', flush=True)
        assert all(p.grad is None for p in ae.parameters()), 'AE weight gradients accumulated'
    print(f'Finished. Selected validation total={best:.6f}; checkpoint={out / "best.pt"}', flush=True)


def image_metrics(image, target_pose, real_future, checker):
    from train_lander_spatial_ae import hard_mask
    from scipy.ndimage import label
    if isinstance(image, torch.Tensor):
        image = image.detach().cpu().permute(1, 2, 0).numpy()
    result = checker(image, *map(float, target_pose))
    def valid(value):
        return float(value) if value is not None and np.isfinite(value) else None
    x, y, theta = [valid(result.get(k)) for k in ('x_err', 'y_err', 'theta_err')]
    if not result['visible']:
        x = y = theta = None
    xo, yo, to = x is not None and x <= .06, y is not None and y <= .1, theta is not None and theta <= .3
    pm, tm = hard_mask(image), hard_mask(real_future)
    union = int((pm | tm).sum())
    components, count = label(pm, structure=np.ones((3, 3)))
    sizes = np.bincount(components.ravel())[1:]
    pixels = int(pm.sum())
    return dict(x_err=x, y_err=y, theta_err=theta, xy_ok=xo and yo, theta_ok=to,
                theta50_ok=to and pixels >= 50, all_ok=xo and yo and to,
                visible=bool(result['visible']), pixel_count=pixels,
                future_mask_iou=float((pm & tm).sum()/union) if union else 1.,
                components=int(count), largest_fraction=float(sizes.max()/pixels) if pixels else 0.,
                rgb_mae=float(np.abs(image-real_future).mean()))


@torch.no_grad()
def pose_probe(ae, data, dev, out, a):
    """Validation-only pose intervention, measured from pixels before training."""
    from constraint_checker import constraint_checker
    out.mkdir(parents=True, exist_ok=True)
    ids = np.random.default_rng(a.seed).choice(len(data['source']), min(32, len(data['source'])), replace=False)
    rows = []
    for number, i in enumerate(ids):
        appearance = data['source'][i:i+1].to(dev)
        pose = data['source_pose'][i:i+1].to(dev)
        shifted, rotated = pose.clone(), pose.clone()
        shifted[:, 0] += .15; rotated[:, 2] += .3
        variants = [decode(ae, p, appearance)[0] for p in (pose, shifted, rotated, data['future_pose'][i:i+1].to(dev))]
        checks = [constraint_checker(im.cpu().permute(1, 2, 0).numpy(), *pose[0].cpu().tolist()) for im in variants]
        x0, x1 = checks[0].get('x_hat'), checks[1].get('x_hat')
        t0, t1 = checks[0].get('theta_hat'), checks[2].get('theta_hat')
        dx = float(x1-x0) if x0 is not None and x1 is not None else None
        dtheta = float(np.arctan2(np.sin(t1-t0), np.cos(t1-t0))) if t0 is not None and t1 is not None else None
        rows.append(dict(pair=int(i), requested_dx=.15, measured_dx=dx,
                         requested_dtheta=.3, measured_dtheta=dtheta))
        if number < a.preview_n:
            target = data['future_rgb'][i].float().permute(2, 0, 1)/255.
            future_ae = decode(ae, data['future_encoded_pose'][i:i+1].to(dev), data['future'][i:i+1].to(dev))[0]
            render_panel(out/f'pair_{i:06d}.png', variants+[target, future_ae],
                         ['Source AE', 'Pose x +0.15 (appearance fixed)', 'Pose theta +0.30 (appearance fixed)',
                          'Source grid + real future pose', 'Real future', 'AE of real future'])
    write_json(out/'measurements.json', rows)
    dxs = [r['measured_dx'] for r in rows if r['measured_dx'] is not None and np.isfinite(r['measured_dx'])]
    angles = [r['measured_dtheta'] for r in rows if r['measured_dtheta'] is not None and np.isfinite(r['measured_dtheta'])]
    print(f'Pose probe: requested dx=0.15, measured median={np.median(dxs) if dxs else None}; '
          f'requested dtheta=0.30, measured median={np.median(angles) if angles else None}', flush=True)
    print('Pose supervision does not guarantee independent pixel control; inspect pose_probe images.', flush=True)


def aggregate(records):
    output = {}
    model_names = list(records[0]['metrics']) if records else []
    for group in ('all_pairs', 'future_detectable', 'future_near', 'future_far'):
        selected = [r for r in records if group == 'all_pairs'
                    or group == 'future_detectable' and r['future_detectable']
                    or group == 'future_near' and r['future_detectable'] and r['future_near']
                    or group == 'future_far' and r['future_detectable'] and not r['future_near']]
        output[group] = {}
        for name in model_names:
            metrics = [r['metrics'][name] for r in selected]
            entry = dict(n=len(metrics))
            for key in ('xy_ok', 'theta_ok', 'theta50_ok', 'all_ok'):
                entry[key] = sum(m[key] for m in metrics)
                entry[key+'_rate'] = entry[key]/len(metrics) if metrics else None
            for key in ('x_err', 'y_err', 'theta_err', 'future_mask_iou', 'components', 'largest_fraction', 'rgb_mae'):
                vals = [m[key] for m in metrics if m[key] is not None]
                entry[key+'_mean'] = float(np.mean(vals)) if vals else None
            output[group][name] = entry
    return output


def load_dynamics(path, project, dev):
    root = Path(project).resolve()
    # Existing HPG runs use old_discrete_dynamics; a repository checkout uses
    # dynamic/lunar_discrete.py. Prefer the original implementation if present.
    candidates = [root / folder / filename
                  for filename in ('old_discrete_dynamics.py', 'lunar_discrete.py')
                  for folder in ('PIWM/dynamic', 'dynamic')]
    implementation = next((p for p in candidates if p.is_file()), None)
    if implementation is None:
        raise FileNotFoundError(f'No discrete dynamics implementation under {root}')
    spec = importlib.util.spec_from_file_location('spatial_discrete_dynamics', implementation)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    model = module.LunarLanderDynamicsDiscrete(learnable=False).to(dev)
    payload = load_pt(path)
    model.load_state_dict(payload['model_state_dict'], strict=True)
    model.eval().requires_grad_(False)
    print(f'Dynamics loaded from {path}; implementation={module.__file__}', flush=True)
    return model


def sample(a):
    from constraint_checker import constraint_checker
    from train_lander_spatial_ae import hard_mask
    seed_all(a.seed)
    dev, out = device(), Path(a.out).resolve()
    if (out/'summary.json').exists():
        raise FileExistsError(f'Evaluation output already exists: {out}')
    (out/'images').mkdir(parents=True, exist_ok=True)
    saved = load_pt(a.diffusion_checkpoint)
    manifest = cache_manifest(a.cache)
    if saved.get('format') != FORMAT or saved['cache_sha256'] != file_hash(Path(a.cache)/'manifest.json'):
        raise ValueError('Diffusion checkpoint does not match this prepared cache')
    verify_cache_files(a.cache, manifest, (a.split,))
    ae, ae_info = load_ae(a.ae_checkpoint, dev, saved['ae_sha256'])
    dataset = CachedPairs(Path(a.cache)/f'{a.split}.pt', ae_info['sha256'])
    data = dataset.data
    model = SpatialDenoiser(**saved['model_config']).to(dev)
    model.load_state_dict(saved['ema'], strict=True); model.eval().requires_grad_(False)
    norm = {k: v.to(dev) for k, v in saved['normalization'].items()}
    schedule = Schedule(saved['settings']['diffusion_steps'], dev)
    dyn = None
    if a.pose_mode in ('dynamics', 'both'):
        if data['horizon'] != 2 or data['pose_columns'] != [0, 1, 4]:
            raise ValueError('Existing two-state dynamics requires horizon 2 and pose columns 0,1,4')
        dyn = load_dynamics(a.dynamics_checkpoint, a.project, dev)
    indices = np.arange(len(dataset))
    if a.max_pairs and len(indices) > a.max_pairs:
        indices = np.sort(np.random.default_rng(a.seed).choice(len(indices), a.max_pairs, replace=False))
    config = dict(settings=vars(a), diffusion_epoch=saved['epoch'], ae=ae_info,
                  diffusion_sha256=file_hash(a.diffusion_checkpoint), pairs=len(indices),
                  checker_path=sys.modules['constraint_checker'].__file__,
                  checker_sha256=file_hash(sys.modules['constraint_checker'].__file__),
                  main_metrics='Against true future pose; missing landers remain failures',
                  theta_min_pixels='native unchanged checker; separate theta50_ok for partner convention',
                  oracle='True future pose provided, future appearance/image withheld from sampler',
                  dynamics='Two observed states and intervening action predict future pose',
                  sampling='One fixed-noise sample per pair; no best-of-N selection or pose GD')
    if dyn is not None:
        config['dynamics_sha256'] = file_hash(a.dynamics_checkpoint)
    write_json(out/'config.json', config)
    print(json.dumps(config, indent=2), flush=True)
    records, episode_cache = [], {}
    for number, i in enumerate(indices, 1):
        b = {k: data[k][i:i+1].to(dev) for k in ('source', 'future', 'source_pose', 'future_pose',
                                               'future_encoded_pose', 'context_raw', 'actions')}
        archive, episode, frame = map(int, data['identity'][i].tolist())
        path = data['files'][archive]['path']
        if path not in episode_cache:
            if file_hash(path) != data['files'][archive]['sha256']:
                raise ValueError(f'Trajectory changed since cache preparation: {path}')
            episode_cache.clear()  # Avoid holding every archive in RAM.
            episode_cache[path] = load_episodes(path)
        source_rgb = episode_cache[path][episode][0][frame].astype(np.float32)/255.
        future_rgb = data['future_rgb'][i].numpy().astype(np.float32)/255.
        actual_pose = data['future_pose'][i].numpy()
        with torch.no_grad():
            source_ae = decode(ae, b['source_pose'], b['source'])[0]
            future_ae = decode(ae, b['future_encoded_pose'], b['future'])[0]
            future_grid_requested = decode(ae, b['future_pose'], b['future'])[0]
        outputs = dict(real_future=future_rgb, future_ae=future_ae,
                       future_grid_true_pose=future_grid_requested)
        requested, request_metrics = {}, {}
        identity = f'{data["files"][archive]["sha256"]}:{episode}:{frame}'
        pair_seed = (a.seed + int(hashlib.sha256(identity.encode()).hexdigest()[:8], 16)) % (2**63-1)
        generator = torch.Generator(device=dev).manual_seed(pair_seed)
        noise = torch.randn(b['source'].shape, device=dev, generator=generator)
        modes = ('oracle', 'dynamics') if a.pose_mode == 'both' else (a.pose_mode,)
        for mode in modes:
            if mode == 'oracle':
                pose = b['future_pose']
            else:
                with torch.no_grad():
                    prediction = dyn(b['context_raw'][:, 0], b['context_raw'][:, 1], b['actions'][:, 1].long())
                if not torch.isfinite(prediction).all():
                    raise RuntimeError('Nonfinite dynamics prediction')
                pose = torch.from_numpy(physical_pose(prediction.cpu().numpy(), data['pose_columns'], data['xy_scales'], data['xy_offsets'])).to(dev)
            requested[mode] = pose[0].cpu().tolist()
            with torch.no_grad():
                swap = decode(ae, pose, b['source'])[0]
                grid, _ = sample_grid(model, schedule, b['source'], b['source_pose'], pose,
                                      b['context_raw'], b['actions'], norm, a.sample_steps, noise, a.clip_x0)
                generated = decode(ae, pose, grid)[0]
            outputs[f'pose_swap_{mode}'], outputs[f'diffusion_{mode}'] = swap, generated
            request_metrics[f'diffusion_{mode}'] = image_metrics(generated, requested[mode], future_rgb, constraint_checker)
        metrics = {name: image_metrics(image, actual_pose, future_rgb, constraint_checker) for name, image in outputs.items()}
        target_mask = hard_mask(future_rgb)
        ys = np.where(target_mask)[0]
        records.append(dict(path=path, episode=episode, source_frame=frame, future_frame=frame+data['horizon'],
                            target_pose=actual_pose.tolist(), requested_pose=requested, seed=pair_seed,
                            future_detectable=bool(len(ys) >= 20), future_near=bool(len(ys) and ys.mean()/96 >= .65),
                            metrics=metrics, against_requested_pose=request_metrics))
        if number <= a.save_n:
            images = [source_rgb, source_ae, future_rgb, future_ae, future_grid_requested]
            titles = ['Real source i', 'Source spatial AE', f'Real future i+{data["horizon"]}',
                      'AE of real future (reference)', 'Real-future grid + true pose (reference)']
            for mode in modes:
                for name in (f'pose_swap_{mode}', f'diffusion_{mode}'):
                    m = metrics[name]
                    theta = 'missing' if m['theta_err'] is None else f'{m["theta_err"]:.3f}'
                    images.append(outputs[name]); titles.append(f'{name}\nIoU={m["future_mask_iou"]:.3f} theta={theta}')
            render_panel(out/'images'/f'pair_{number:05d}.png', images, titles)
        if number % 20 == 0 or number == len(indices):
            write_json(out/'measurements.json', records)
            write_json(out/'summary.json', aggregate(records))
            print(f'Evaluated {number}/{len(indices)} pairs', flush=True)
    summary = aggregate(records)
    print('\nFINAL FUTURE-FRAME RESULTS (all sampled pairs, missing outputs fail):', flush=True)
    for name, row in summary.get('all_pairs', {}).items():
        n = row['n']
        print(f'{name}: xy={row["xy_ok"]}/{n} ({100*row["xy_ok_rate"]:.1f}%); '
              f'theta={row["theta_ok"]}/{n} ({100*row["theta_ok_rate"]:.1f}%); '
              f'all={row["all_ok"]}/{n} ({100*row["all_ok_rate"]:.1f}%); '
              f'future IoU={row["future_mask_iou_mean"]:.4f}', flush=True)
    with zipfile.ZipFile(out/'comparisons.zip', 'w', zipfile.ZIP_DEFLATED) as archive:
        for p in sorted((out/'images').glob('*.png')):
            archive.write(p, p.relative_to(out))
    print(f'Results: {out / "summary.json"}\nImages: {out / "comparisons.zip"}', flush=True)


def self_test():
    import tempfile
    from spatial_diffusion_data import self_test as data_test
    from train_lander_spatial_ae import SpatialLanderAE
    seed_all(42); torch.set_num_threads(2); data_test()
    dev = torch.device('cpu')
    schedule = Schedule(100, dev)
    clean, noise = torch.randn(2, 16, 6, 8), torch.randn(2, 16, 6, 8)
    t = torch.tensor([0, 50])
    noisy = schedule.add_noise(clean, t, noise)
    assert torch.allclose(schedule.clean(noisy, t, noise), clean, atol=1e-5)
    assert (schedule.alpha[1:] < schedule.alpha[:-1]).all() and schedule.alpha[-1] > 0
    source_pose, future_pose = torch.zeros(2, 3), torch.ones(2, 3)
    context, actions = torch.zeros(2, 2, 8), torch.tensor([[0, 1], [2, 3]])
    cond = condition(source_pose, future_pose, context, actions)
    assert cond.shape == (2, 32)
    norm = dict(mean=torch.zeros(1, 16, 1, 1), std=torch.ones(1, 16, 1, 1),
                cond_mean=torch.zeros(1, 32), cond_std=torch.ones(1, 32))
    ae = SpatialLanderAE(16).eval().requires_grad_(False)
    ae_before = {k: v.clone() for k, v in ae.state_dict().items()}
    model = SpatialDenoiser(16, 32, width=32, blocks=2)
    optimizer = torch.optim.Adam(model.parameters(), lr=.001)
    # Meaningful smoke optimization on a fixed epsilon target.
    start = float(F.mse_loss(model(noisy, t, clean, cond), noise).detach())
    for _ in range(4):
        optimizer.zero_grad()
        estimate = model(noisy, t, clean, cond)
        recovered = schedule.clean(noisy, t, estimate)
        image = decode(ae, future_pose, recovered)
        loss = F.mse_loss(estimate, noise) + .01*image.square().mean()
        loss.backward(); optimizer.step()
    assert F.mse_loss(model(noisy, t, clean, cond), noise).item() < start
    assert all(p.grad is None for p in ae.parameters())
    assert all(torch.equal(ae_before[k], v) for k, v in ae.state_dict().items())
    sampled, _ = sample_grid(model, schedule, clean, source_pose, future_pose,
                             context, actions, norm, 20, noise.clone())
    assert sampled.shape == clean.shape and torch.isfinite(sampled).all()
    # Perfect-epsilon oracle must recover clean data through skipped DDIM jumps.
    class PerfectNoise(nn.Module):
        def forward(self, latent, time, source, cond):
            alpha = schedule.alpha[time].view(-1, 1, 1, 1)
            return (latent - alpha.sqrt()*clean) / (1-alpha).sqrt()
    exact, _ = sample_grid(PerfectNoise(), schedule, clean, source_pose, future_pose,
                           context, actions, norm, 20, noise, clip=0.)
    assert torch.allclose(exact, clean, atol=1e-4), 'Wrong DDIM previous-alpha jump'
    target = torch.zeros(2, 96, 128, 3, dtype=torch.uint8)
    target[:, 40:47, 57:65] = torch.tensor([120, 40, 200], dtype=torch.uint8)
    target[:, 47:53, 57:59] = torch.tensor([120, 40, 200], dtype=torch.uint8)
    prediction = (target.permute(0, 3, 1, 2).float()/255.).requires_grad_(True)
    shape, rgb = auxiliary_loss(prediction, target)
    gradient = torch.autograd.grad(shape+rgb, prediction)[0]
    assert torch.isfinite(gradient).all() and gradient.abs().sum() > 0
    with tempfile.TemporaryDirectory() as directory:
        p = Path(directory)/'test.pt'
        save_pt(p, dict(model=model.state_dict(), normalization=norm))
        twin = SpatialDenoiser(16, 32, width=32, blocks=2)
        twin.load_state_dict(load_pt(p)['model'], strict=True)
        assert torch.equal(model(noisy, t, clean, cond), twin(noisy, t, clean, cond))
    print('DIFFUSION SELF-TEST PASSED: noise inversion, conditional learning, frozen AE, latent gradient, DDIM jump oracle, shape gradients, checkpoint round trip.', flush=True)


